export const INITIAL_STUDENTS: Student[] = Object.entries(RAW_STUDENT_NAMES_BY_CLASS).flatMap(
  ([clsId, studentList], clsIdx) => {
    const classObj = INITIAL_CLASSES.find((c) => c.id === clsId);
    const className = classObj?.name || `Kelas ${clsId.replace('cls-', '').replace('-', '.')}`;
    const gradeLevel = classObj?.gradeLevel || 7;
    const yearPrefix = gradeLevel === 7 ? '25' : gradeLevel === 8 ? '24' : '23';

    return studentList.map((st, stIdx) => {
      const idxGlobal = clsIdx * 10 + stIdx + 1;
      const numStr = String(idxGlobal).padStart(3, '0');
      const nis = `${yearPrefix}07${String(stIdx + 1).padStart(2, '0')}`;
      const nisn = `00${9 - (gradeLevel - 7)}9123${numStr}`;

      return {
        id: `std-${clsId}-${stIdx + 1}`,
        nis,
        nisn,
        name: st.name,
        gender: st.gender,
        birthPlace: stIdx % 2 === 0 ? 'Semarang' : 'Kendal',
        birthDate: `${10 + (stIdx % 18)} Mei 201${12 - gradeLevel}`,
        religion: (() => {
          const lowerName = st.name.toLowerCase();
          if (lowerName.includes('christopher') || lowerName.includes('jessica') || lowerName.includes('calvin')) {
            return 'Kristen';
          }
          if (lowerName.includes('gita nirmala') || lowerName.includes('oktavianus') || lowerName.includes('gisela')) {
            return 'Katolik';
          }
          if (lowerName.includes('rian bagus') || lowerName.includes('galang rambu') || lowerName.includes('yoga pratama')) {
            return 'Hindu';
          }
          if ((lowerName.includes('nayla salsabila') && clsId === 'cls-7-1') || lowerName.includes('kevin sanjaya') || lowerName.includes('candra wijaya') || lowerName.includes('xena')) {
            return 'Buddha';
          }
          return 'Islam';
        })(),
        classId: clsId,
        className,
        parentName: `Bpk/Ibu ${st.name.split(' ')[0]}`,
        parentPhone: `081223344${String(idxGlobal).padStart(3, '0')}`,
        address: `Jl. Pendidikan No. ${stIdx + 1}, Semarang`,
      };
    });
  }
);

