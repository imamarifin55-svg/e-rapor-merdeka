export const INITIAL_GRADES: GradeRecord[] = INITIAL_STUDENTS.flatMap((st, sIdx) => {
  // Hanya masukkan mapel yang diambil oleh siswa (1 mapel agama yang sesuai + seluruh mapel non-agama)
  const studentSubjects = INITIAL_SUBJECTS.filter((sub) => {
    if (isReligionSubject(sub)) {
      const subRel = getSubjectReligion(sub);
      return subRel === st.religion;
    }
    return true;
  });

  return studentSubjects.map((sub, subIdx) => {
    const kktp = sub.kktp || 75;
    // Nilai STS terdistribusi realistis (70 - 96)
    const baseScore = 73 + ((sIdx * 7 + subIdx * 5) % 24);
    const isTuntas = baseScore >= kktp;
    const predikat = baseScore >= 90 ? 'A' : baseScore >= kktp ? 'B' : baseScore >= kktp - 10 ? 'C' : 'D';
    const status = isTuntas ? 'Tuntas' : 'Belum Tuntas';
    const note = isTuntas
      ? `Menunjukkan penguasaan materi yang sangat baik pada asesmen tengah semester (STS) ${sub.name}.`
      : `Memerlukan bimbingan dan pendampingan berkala dalam penguasaan konsep tengah semester ${sub.name} (KKTP: ${kktp}).`;

    return {
      id: `grd-${st.id}-${sub.id}`,
      studentId: st.id,
      subjectId: sub.id,
      classId: st.classId,
      semester: 'Ganjil',
      academicYearId: 'ay-2025-1',
      stsScore: baseScore,
      sumatifTengahSemester: baseScore,
      nilaiAkhir: baseScore,
      catatanSts: note,
      statusSts: status,
      predikatSts: predikat,
      highestCompetencyNarrative: note,
      lowestCompetencyNarrative: isTuntas
        ? 'Memenuhi ketuntasan asesmen tengah semester.'
        : `Belum mencapai kriteria ketercapaian tujuan pembelajaran (${kktp}).`,
    };
  });
});

